-- SkyFraze: люди — каталог зарегистрированных участников («резидентов»).
--
-- Каталог отвечает на вопрос «кто вообще есть на инсталляции». Это витрина
-- человека до знакомства, поэтому сведения живут на самом users, а не на связи
-- соавторов (в отличие от 0005, где crafts — свойство ПАРЫ: за что договорились
-- в общем деле):
--   * bio        — краткое «о себе» (предел 600 рун проверяет auth.Service);
--   * crafts     — специализации: правописание, проработка героя, арт… Список
--                  свободный, каталог подсказок живёт в интерфейсе, поэтому
--                  TEXT[] и обновляется без миграций;
--   * discoverable — галочка «не показывать меня»: скрывает человека и из
--                  каталога, и из поиска соавторов. По умолчанию показываем:
--                  инсталляция — это круг людей, а не набор закрытых профилей.
--
-- Файл идемпотентен: раннер применяет его один раз, но повторный прогон на уже
-- обновлённой базе не должен ломаться (IF NOT EXISTS).

ALTER TABLE users ADD COLUMN IF NOT EXISTS bio TEXT NOT NULL DEFAULT '';
ALTER TABLE users ADD COLUMN IF NOT EXISTS crafts TEXT[] NOT NULL DEFAULT '{}';
ALTER TABLE users ADD COLUMN IF NOT EXISTS discoverable BOOLEAN NOT NULL DEFAULT true;

-- Фильтр каталога по специализации: точное вхождение в массив (craft = ANY(crafts)).
-- GIN, а не btree: колонка — массив, и запрос ищет элемент, а не префикс значения.
CREATE INDEX IF NOT EXISTS idx_users_crafts_gin ON users USING gin (crafts);

