-- 0011_users_is_system — отличать системные аккаунты (агент) от людей.
--
-- Зачем отдельный признак. Миграция 0010 завела ИИ-агенту строку в users, чтобы его
-- правки были подписаны им. Но «сколько людей на инсталляции» и «пустая ли она» считались
-- просто как `COUNT(*) FROM users`: агент попадал в счёт, установка переставала выглядеть
-- пустой, и на ЧИСТОМ стенде пропадало окно первого администратора — форма регистрации
-- показывала «Заявка на доступ», а зарегистрироваться было некому. Нашлось в CI:
-- e2e-сценарии на свежей базе перестали проходить и честно пропускались.
--
-- Поэтому системные аккаунты помечаются явно и исключаются из всех подсчётов «людей»:
-- первый администратор, список пользователей в админке, поток регистрации.

ALTER TABLE users ADD COLUMN IF NOT EXISTS is_system boolean NOT NULL DEFAULT false;

-- Агент — системный: под ним нельзя войти, он не участвует в регистрации и не занимает
-- «первое место» на инсталляции.
UPDATE users SET is_system = true WHERE id = '00000000-0000-0000-0000-0000000000a1';
