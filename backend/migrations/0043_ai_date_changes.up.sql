-- 0043: правка ДАТЫ кадра помощником (третий вид предложения).
--
-- Зачем отдельные колонки, а не old_title/new_title. Дата — не текст: она живёт в документе
-- скалярным полем `event_date` в формате `YYYY-MM-DD`, и «правка текста» её не касается.
-- Положить дату в `old_title` значило бы, что «Вернуть прежний текст» вернёт и дату, и
-- заголовок, — то есть одно нажатие отменит две разные правки.
--
-- Почему text, а не date. В документе и в `<input type="date">` дата — строка `YYYY-MM-DD`.
-- Колонка типа date заставила бы конвертировать туда-обратно на каждом шаге и открыла бы
-- часовые пояса: «2026-03-02» в UTC и в местном времени — разные дни. Строка совпадает с
-- источником истины, а формат проверяется при разборе аргумента инструмента.
ALTER TABLE ai_changes
  ADD COLUMN IF NOT EXISTS old_date text NOT NULL DEFAULT '';

ALTER TABLE ai_changes
  ADD COLUMN IF NOT EXISTS new_date text NOT NULL DEFAULT '';
