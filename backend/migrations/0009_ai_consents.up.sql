-- 0009_ai_consents — согласие человека на отправку текста проекта провайдеру модели.
--
-- Зачем отдельная таблица, если ИИ-помощник и так выключен по умолчанию. Выключенный
-- помощник означает «функции нет»; согласие означает «человек знает, что его текст
-- уходит на чужую машину». Это два разных вопроса, и второй нельзя решить за человека
-- настройкой стенда: админ включает помощник для всех, а текст проекта пишет конкретный
-- пользователь.
--
-- Ключ согласия — (пользователь, провайдер): отправка в локальную модель (Ollama)
-- согласия не требует вовсе (текст не покидает машину), а переход с бесплатного тарифа
-- на платный — это уже другой получатель данных, и спрашиваем снова.
--
-- Строку не удаляем при отзыве: галочку «согласен» человек может снять, и тогда запись
-- исчезает (DELETE), а вот молчаливое согласие «по умолчанию» появиться не должно —
-- поэтому в сервисе проверка идёт строго по наличию строки.

CREATE TABLE IF NOT EXISTS ai_consents (
    user_id    uuid        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    provider   text        NOT NULL,
    agreed_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, provider)
);
