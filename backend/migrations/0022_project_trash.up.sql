-- 0022: корзина проектов — мягкое удаление с восстановлением.
--
-- Зачем. Удаление проекта было жёстким (`DELETE FROM projects`), а вместе с проектом каскадом
-- уходили и события, и вложения, и история версий. То есть «случайно удалил не тот проект» у
-- автора лечилось только ночной копией — единственным механизмом, который для этого не
-- предназначен. Для писателя это самая дорогая ошибка интерфейса: одна кнопка и подтверждение
-- стоят рукописи.
--
-- Как теперь: удаление помечает проект (`deleted_at`), а «навсегда» удаляет только корзина
-- через 30 дней. Пока проект в корзине, он не виден ни в списке, ни в API, ни в публичной
-- ленте — фильтр стоит на чтении проекта и членства, а не в каждом обработчике по отдельности.
--
-- Почему срок 30 дней. Это тот же срок, что у «Вернуть» для правок агента (история версий):
-- месяц — граница, после которой «верни как было» превращается в «откати проект», и обещать
-- это уже нельзя. Корзина не должна становиться вторым архивом.
ALTER TABLE projects ADD COLUMN IF NOT EXISTS deleted_at timestamptz;

-- Список корзины — «мои удалённые, свежие сверху». Частичный индекс: активных проектов
-- всегда большинство, и общий индекс по deleted_at был бы почти пустой.
CREATE INDEX IF NOT EXISTS projects_trashed_idx
    ON projects(owner_id, deleted_at DESC)
    WHERE deleted_at IS NOT NULL;
