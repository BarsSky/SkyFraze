-- 0024: упоминания людей в обсуждении кадров.
--
-- Зачем отдельная таблица, а не разбор `@ник` на лету. Разбор на лету отвечает на вопрос
-- «похоже на упоминание?», а нужен ответ на вопрос «кого это касается». Ник в тексте может
-- быть обращением к человеку, которого в проекте нет, или просто словом с собакой; хранить
-- же надо владельца и участников проекта — тех, кто комментарий вообще увидит.
--
-- Поэтому сервер разбирает ник В МОМЕНТ написания и кладёт сюда только тех, кто участник
-- проекта. Строка живёт ровно столько же, сколько комментарий: каскад по `comment_id` —
-- упоминание без комментария не значит ничего.
--
-- Мягкое удаление комментария (0023) упоминания не удаляет: текст вычищается, и ник в нём
-- исчезает, но «меня упомянули в этом обсуждении» остаётся фактом — и таблица нужна ещё и
-- для этого: после удаления тело пустое, и разобрать упоминание из него уже нельзя.
CREATE TABLE IF NOT EXISTS comment_mentions (
    comment_id uuid        NOT NULL REFERENCES event_comments(id) ON DELETE CASCADE,
    user_id    uuid        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    -- Один человек упомянут в комментарии один раз, сколько бы раз ни встретился ник.
    PRIMARY KEY (comment_id, user_id)
);

-- «Где меня упомянули» — по человеку и свежести.
CREATE INDEX IF NOT EXISTS comment_mentions_user_idx
    ON comment_mentions(user_id, created_at DESC);
