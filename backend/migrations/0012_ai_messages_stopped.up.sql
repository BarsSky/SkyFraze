-- 0012: пометка «ответ остановлен человеком».
--
-- Зачем отдельная колонка, а не приписка в тексте. Кнопка «стоп» обрывает ответ
-- посередине: часть текста уже показана человеку и должна остаться в истории — иначе
-- следующий вопрос потеряет контекст сказанного. Но история уходит модели, и служебная
-- приписка («...остановлено») выглядела бы для неё частью ответа. Поэтому признак живёт
-- отдельно: интерфейс по нему пишет «остановлено», модель видит только сам текст.
ALTER TABLE ai_messages ADD COLUMN IF NOT EXISTS stopped boolean NOT NULL DEFAULT false;
