-- SkyFraze: дедупликация файлов по содержимому.
--
-- Зачем. Один и тот же файл попадает в проект несколько раз: картинку загружают
-- повторно, ту же папку импортируют в два проекта, копию архива переносят на
-- другой стенд. Байты при этом одни и те же, и хранить их дважды незачем.
--
-- Как. У вложения появляется хеш содержимого (SHA-256). При записи файла сервер
-- сначала считает хеш и, если файл с таким же содержимым уже есть, НЕ пишет
-- второй: строка `assets` начинает указывать на существующий объект хранилища
-- (s3_key). Имя файла, владелец и проект при этом у каждой строки свои — общим
-- становится только сам файл.
--
-- Почему не отдельная таблица `blobs`. Уборщик хранилища (maintenance.Sweeper)
-- уже считает файл ненужным, когда на его ключ не ссылается ни одна строка
-- `assets`. Значит, достаточно разделить ключ между строками: ссылок нет —
-- файл удаляется, а пока ссылка есть, он живёт. Отдельная таблица добавила бы
-- вторую точку правды и переезд файлов существующих проектов.
--
-- Хеш может быть пустым: у вложений, загруженных до этой миграции, и у файлов,
-- которые сервер получил из архива переноса (там свой идентификатор и своя
-- запись), содержимое задним числом не пересчитывается.

ALTER TABLE assets ADD COLUMN IF NOT EXISTS content_hash TEXT;

-- Поиск «есть ли уже такой файл» идёт по хешу, поэтому индекс обязателен: иначе
-- каждая загрузка превращалась бы в обход всей таблицы вложений.
CREATE INDEX IF NOT EXISTS idx_assets_content_hash ON assets (content_hash);

-- Уникальность ключа снимается: она означала «у каждой строки свой файл», а теперь
-- файл может быть общим для нескольких строк — ровно в этом и смысл дедупликации.
-- Тождество файла теперь задаёт содержимое (content_hash), а не его адрес; ключ
-- остаётся просто местом в хранилище.
ALTER TABLE assets DROP CONSTRAINT IF EXISTS assets_s3_key_key;

-- Поиск «ссылается ли кто-нибудь ещё на этот ключ» нужен при удалении проекта:
-- файл, которым пользуются два проекта, нельзя удалять вместе с одним из них.
CREATE INDEX IF NOT EXISTS idx_assets_s3_key ON assets (s3_key);
