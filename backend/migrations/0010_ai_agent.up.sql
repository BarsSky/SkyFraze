-- 0010_ai_agent — ИИ-помощник как соавтор проекта: своё имя, роль и поведение.
--
-- Зачем агент становится отдельной записью в users. Помощник правит текст проекта —
-- значит, он участник на тех же правах, что соавторы: его правки должны быть
-- подписаны ИМ, а не человеком, который нажал «спросить». Иначе в истории правок
-- («кто это написал?») появлялся бы владелец проекта, который этого не писал, а
-- список участников не показывал бы, что в проекте работает ещё один автор.
--
-- Поэтому здесь две вещи:
--   1. системный пользователь агента с ФИКСИРОВАННЫМ идентификатором и именем —
--      его нельзя зарегистрировать или войти под ним (хеш пароля недействителен),
--      он не ищется в каталоге резидентов и не мешает уникальности ников;
--   2. настройки агента НА ПРОЕКТ: роль и указания владельца. Поведение помощника —
--      свойство проекта, а не стенда: в одной истории нужен строгий летописец, в
--      другой — соавтор-фантаст, и это решает владелец проекта, а не админ.
--
-- Идентификатор агента намеренно «человеческий» по смыслу (…-a1), но фиксированный:
-- по нему в коде узнаётся автор правки, и он не должен меняться между обновлениями.

