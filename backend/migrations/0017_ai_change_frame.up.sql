-- 0017: снимок кадра в предложении удаления — чтобы удаление можно было отменить.
--
-- Зачем. До этого «Вернуть» было только у перезаписи (текст лежал в old_title/old_body), а
-- удаление считалось необратимым: восстановить кадр — это вставка с прежним идентификатором
-- и местом в дереве, а этих данных в предложении не было. В итоге человек, согласившийся на
-- удаление, терял кадр окончательно — при том что подтверждение как раз и обещает
-- «передумать можно».
--
-- Что здесь: frame — снимок кадра в момент удаления: идентификатор, родитель, позиция в
-- дереве, дата, вложения, фон и created_at (заголовок и текст в old_title/old_body, но в
-- снимке они тоже есть — снимок самодостаточен, и его можно разобрать, не заглядывая в
-- соседние колонки). Одним jsonb, а не семью колонками: это непрозрачный для запросов
-- снимок одного кадра, и читается он только при возврате.
ALTER TABLE ai_changes ADD COLUMN IF NOT EXISTS frame jsonb;
