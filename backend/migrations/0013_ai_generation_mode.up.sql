-- 0013: режим генерации и стиль иллюстраций на проект.
--
-- Зачем это отдельными полями, а не «одним выключателем». У агента две разные
-- возможности: писать текст (главы, под-события) и рисовать картинки. Текстовую модель
-- стенд имеет почти всегда, генератор изображений — отдельный сервис со своим железом, и
-- он может быть не настроен, выключен или занят. Поэтому владельцу нужен ВЫБОР:
--
--   auto   — как получится: оба, если генератор доступен, иначе только текст (по умолчанию);
--   text   — только текст: картинки агент не предлагает и не делает, даже если умеет;
--   images — только картинки: иллюстрации без правки текста;
--   both   — оба: агент может и написать главу, и нарисовать к ней иллюстрацию.
--
-- image_style — стиль иллюстраций словами («акварель, тёплый свет, без текста»). Он
-- дописывается сервером в каждый промпт: без него каждая картинка была бы в своей манере,
-- и агент изобретал бы стиль заново на каждый запрос.
ALTER TABLE project_ai_settings
  ADD COLUMN IF NOT EXISTS generation text NOT NULL DEFAULT 'auto';

ALTER TABLE project_ai_settings
  ADD COLUMN IF NOT EXISTS image_style text NOT NULL DEFAULT '';
