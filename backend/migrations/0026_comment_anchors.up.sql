-- 0026: якоря комментариев к фрагменту текста.
--
-- Задача. Замечание сейчас ставится к кадру целиком. Правки же идут по абзацам: «здесь
-- провал в логике» относится к конкретным двум строкам, а не к главе.
--
-- Почему не «смещение в символах». Текст кадра живёт в CRDT (`Y.Text` в документе Yjs), и
-- вставка абзаца выше сдвигает все смещения — замечание молча переезжает на другой текст,
-- оставаясь «валидным» по форме. Поэтому хранится `Y.RelativePosition` — позиция, привязанная
-- к конкретным символам CRDT, а не к номеру (docs/fragment-comments.md §4: якорь пережил
-- вставку 11 знаков до него, остался на том же тексте).
--
-- Почему отдельная таблица, а не колонки в `event_comments`. «Нет строки здесь» — это и есть
-- замечание к кадру целиком: один механизм вместо двух, и старые комментарии не мигрируют.
--
-- Зачем `quote`. Не для позиционирования (для этого якорь), а для человека: когда фрагмент
-- удалён или кадр переписан, якорь резолвится в пустоту — и без сохранённой цитаты замечание
-- невозможно прочитать. Цитата — то, что было выделено в момент написания.
CREATE TABLE IF NOT EXISTS comment_anchors (
    comment_id   uuid  PRIMARY KEY REFERENCES event_comments(id) ON DELETE CASCADE,
    -- Поле, к которому относится якорь. Пока только `body`: выделение в заголовке —
    -- отдельная мелочь интерфейса, и смешивать её с основной задачей незачем.
    field        text  NOT NULL DEFAULT 'body',
    -- Y.RelativePosition в том виде, в каком его отдаёт Y.encodeRelativePosition:
    -- 11 байт на наш документ (измерено), байт-совместимо с клиентом.
    start_relpos bytea NOT NULL,
    end_relpos   bytea NOT NULL,
    quote        text  NOT NULL DEFAULT '',
    created_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT comment_anchors_field_check CHECK (field IN ('body', 'title'))
);

-- Непустой диапазон проверяется не здесь: якорь — это относительные позиции, и «пусто»
-- определяется только резолвом в текущем документе (схлопнувшийся якорь — законное
-- состояние: текст фрагмента удалили). Схема хранит то, что прислали, а не догадку.
