-- 0016: история версий проекта.
--
-- Зачем. Сейчас у проекта ОДИН снапшот, и он перезаписывается: `project_event_state`
-- хранит последнее состояние (у каталога промптов на стенде ревизия 302), а всё, что было
-- до, живёт только в памяти живой комнаты. Ни CRDT, ни копии этого не заменяют:
--   - CRDT помнит историю, пока кто-то держит документ в памяти, и никогда не «отменяет»
--     правку — он сливает;
--   - копии снимаются раз в сутки и лежат файлами, то есть «верни как было час назад» по
--     ним не сделать (и достать один проект из дампа без операции — работа на полчаса).
--
-- Поэтому версии живут отдельными строками: снапшот (тот же формат Yjs), время, автор и
-- вид («авто» — снят сервером по ходу правок, «ручной» — кнопкой человека).
--
-- Почему снапшот целиком, а не диффы. Диффы меньше, но чтобы их применить, нужна цепочка
-- от базового состояния: порванная цепочка (сработало удержание по объёму) делает
-- бесполезными все последующие версии. Снапшот — 361 КБ у самого большого проекта, а
-- удержание (сколько версий и сколько мегабайт) решает ту же задачу прямо и предсказуемо.
CREATE TABLE IF NOT EXISTS project_revisions (
    id         uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    project_id uuid        NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    -- yjs_state — состояние документа на момент версии (формат тот же, что в
    -- project_event_state), events — сколько кадров было (для списка без разбора).
    yjs_state  bytea       NOT NULL,
    events     integer     NOT NULL DEFAULT 0,
    -- checksum — чтобы автоснимок не плодил версии, когда ничего не менялось.
    checksum   text        NOT NULL DEFAULT '',
    -- kind: auto (сервер сам) | manual (человек нажал «Сохранить версию»).
    kind       text        NOT NULL DEFAULT 'auto',
    label      text        NOT NULL DEFAULT '',
    created_by uuid        REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- Список версий всегда читается «для проекта, новые сверху».
CREATE INDEX IF NOT EXISTS project_revisions_project_idx
    ON project_revisions(project_id, created_at DESC);
