-- 0025: реакции на замечания — «согласен» и «сделано».
--
-- Зачем это, если в обсуждении можно ответить словами. Половина ответов в критике — не текст,
-- а согласие: «да, поправлю». Писать ради этого сообщение — шум и для автора, и для читателя:
-- в ветке появляется строка, которая ничего не добавляет к разговору. Реакция фиксирует факт
-- одним нажатием и не занимает место в ветке.
--
-- Почему ровно два вида и именно такие. Оба — про работу, а не про человека: «согласен»
-- (замечание принято к работе) и «сделано» (правка внесена). Оценки «нравится / не нравится»
-- здесь были бы вредны: замечание — это не пост в соцсети, и голосование за него превращает
-- критику в рейтинг. Поэтому набор фиксирован `CHECK`-ом, а не «любой эмодзи».
--
-- Первичный ключ (comment_id, user_id, kind): один человек может поставить и «согласен», и
-- «сделано» — это разные состояния одного замечания, а не альтернативы. Повторное нажатие
-- снимается отдельным DELETE, а не переключателем: явные PUT/DELETE безопасно повторять.
CREATE TABLE IF NOT EXISTS comment_reactions (
    comment_id uuid        NOT NULL REFERENCES event_comments(id) ON DELETE CASCADE,
    user_id    uuid        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind       text        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (comment_id, user_id, kind),
    CONSTRAINT comment_reactions_kind_check CHECK (kind IN ('agree', 'done'))
);
