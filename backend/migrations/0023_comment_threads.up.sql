-- 0023: ответы ветками в обсуждении кадров и мягкое удаление комментария.
--
-- Зачем ветки. Плоское обсуждение кадра читается, пока в нём два-три замечания. Дальше
-- разговор рассыпается: ответ на замечание стоит ниже всех, и уже непонятно, на что он
-- отвечает, — а именно это в критике текста и важно.
--
-- Почему ветка ОДНОГО уровня. Ответ на ответ в узкой панели под кадром превращается в
-- лесенку отступов, где на телефоне приходится по 12 знаков на строку. Один уровень
-- («замечание — ответы») покрывает разговор двух-трёх человек, а глубже начинается
-- отдельный продукт — форум. Сервер это и проверяет: `parent_id` может указывать только
-- на корневой комментарий.
--
-- Почему удаление стало мягким (`deleted_at`). Раньше `DELETE` уносил строку целиком. С
-- ветками это значило бы, что автор замечания, удалив своё, стирает и ЧУЖИЕ ответы — или,
-- при `ON DELETE CASCADE`, теряет ветку целиком. Поэтому строка остаётся, тело
-- вычищается, а в интерфейсе на её месте «Комментарий удалён»: разговор сохраняет смысл,
-- слова человека — нет.
ALTER TABLE event_comments
    ADD COLUMN IF NOT EXISTS parent_id uuid REFERENCES event_comments(id) ON DELETE CASCADE;

ALTER TABLE event_comments
    ADD COLUMN IF NOT EXISTS deleted_at timestamptz;

-- Ответы кадра ищутся по родителю («все ответы на это замечание»).
CREATE INDEX IF NOT EXISTS event_comments_parent_idx
    ON event_comments(parent_id, created_at)
    WHERE parent_id IS NOT NULL;

-- Счётчики и непрочитанное считают только живые комментарии: индекс под этот фильтр.
CREATE INDEX IF NOT EXISTS event_comments_live_idx
    ON event_comments(event_id, created_at)
    WHERE deleted_at IS NULL;
