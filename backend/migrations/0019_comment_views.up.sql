-- 0019: прочитанность обсуждения — чтобы новые замечания было видно, не открывая проект.
--
-- Зачем. Комментарий, который никто не заметил, равен неотправленному письму: человек
-- заходит в проект, чтобы писать текст, а не проверять, не ответили ли ему под кадром.
-- Без метки «прочитано» единственный способ узнать о замечании — открыть каждый кадр.
--
-- Почему отметка на кадр, а не на проект. Обсуждение идёт под конкретным кадром, и «я
-- прочитал замечания к этой главе» не значит «я прочитал во всём проекте»: проект — это
-- десятки кадров, и обнулять все счётчики при открытии одного из них было бы обманом.
--
-- Ключ — (user_id, event_id): одна строка на человека и кадр, а не журнал просмотров.
-- История «кто когда открывал разговор» здесь не нужна и была бы слежкой.
CREATE TABLE IF NOT EXISTS comment_views (
    user_id  uuid        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    event_id uuid        NOT NULL,
    seen_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, event_id)
);

-- Непрочитанное считается по человеку и кадру; обратный индекс — чтобы уборка могла
-- снести отметки к исчезнувшим кадрам, не читая всю таблицу.
CREATE INDEX IF NOT EXISTS comment_views_event_idx ON comment_views(event_id);
