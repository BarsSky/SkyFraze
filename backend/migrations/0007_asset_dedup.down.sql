-- Откат 0007: у вложений убирается хеш содержимого.
--
-- Файлы при этом не трогаем: строки `assets` указывают на свои ключи, и после
-- отката каждая строка снова считается «своим» файлом. Общие файлы (когда две
-- строки ссылались на один объект) продолжат работать, но уборщик хранилища
-- больше не увидит их общими — он и раньше удалял ключ только при отсутствии
-- ссылок, поэтому данные не потеряются.

DROP INDEX IF EXISTS idx_assets_s3_key;
DROP INDEX IF EXISTS idx_assets_content_hash;
ALTER TABLE assets DROP COLUMN IF EXISTS content_hash;
