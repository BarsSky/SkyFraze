-- 0042: негативный промпт на проект.
--
-- Зачем. До этой миграции «чего не должно быть на картинке» задавал только админ стенда
-- (`AI_IMAGE_NEGATIVE` в окружении). Это работало, пока стиль был один на инсталляцию, но
-- негативный промпт — часть авторского замысла, а не свойство сервера: в одном проекте это
-- «текст, водяные знаки, современная одежда», в другом — «люди вообще». Автор знает это лучше
-- администратора и меняет по ходу книги.
--
-- Почему пустая строка по умолчанию, а не «копия стенда». Пустое значение читается как «не
-- задано»: сервер подставит негативный промпт стенда (`AI_IMAGE_NEGATIVE`). Так один и тот же
-- проект ведёт себя одинаково на стендах с разными настройками, а заданное автором значение
-- ничего не теряет при переезде.
ALTER TABLE project_ai_settings
  ADD COLUMN IF NOT EXISTS image_negative text NOT NULL DEFAULT '';
