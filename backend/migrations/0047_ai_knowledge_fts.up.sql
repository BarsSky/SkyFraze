-- 0047: морфологический поиск по знаниям (0.153.0).
--
-- Зачем полнотекстовый индекс. Триграммы (0046) находят опечатки и близкие формы, но не
-- морфологию: «дракон» ↔ «драконы» да, а «драконами» — уже плохо. У PostgreSQL есть
-- словарь `russian` со snowball-стеммером: он приводит словоформы к одной основе, не
-- требуя ни внешнего поисковика, ни лемматизации в коде.
--
-- Почему своя функция для меток. `array_to_string(anyarray, text)` помечена STABLE
-- (вывод элементов зависит от типа), и в индексе её использовать нельзя. Для text[] вывод
-- детерминирован, поэтому обёртка объявлена IMMUTABLE — иначе выражение индекса не создать.
--
-- Индекс — по ВЫРАЖЕНИЮ, и оно обязано совпадать с тем, что считает
-- `store.ListAIKnowledge`: заголовок + пометка + тело + метки одной строкой. Менять одно
-- без другого нельзя — расхождение оставит запрос без индекса (и это будет незаметно).
CREATE OR REPLACE FUNCTION sf_tags_text(text[]) RETURNS text
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  AS $$ SELECT array_to_string($1, ' ') $$;

CREATE INDEX IF NOT EXISTS ai_knowledge_fts_idx
  ON ai_knowledge USING gin (
    to_tsvector('russian', title || ' ' || summary || ' ' || body || ' ' || sf_tags_text(tags))
  );
