package collab

// ack.go — подтверждение приёма правки (0.140.0).
//
// Зачем. До 0.140.0 клиент узнавал о судьбе своей правки только косвенно: `readyState === OPEN`
// не доказывает, что сервер апдейт получил (прокси без Upgrade, полуоткрытое соединение), а
// подтверждением считалась запись снапшота по REST. Отсюда правило 0.138.0: «если тишина дольше
// 10 с — пиши состояние по REST», то есть один PUT на редактора раз в 10 с и окно потери до 10 с
// на случай, когда сокет молчит, а апдейты уходят в пустоту.
//
// Теперь на каждый апдейт сервер отвечает подтверждением: «вот номер — эта правка уже в документе
// комнаты». Клиент перестаёт писать снапшот по REST, пока подтверждения приходят, и оставляет
// запись как страховку на случай, когда их нет (старый сервер, прокси режет обратный канал).
// Долговечность при этом даёт обычный тик комнаты (5 с) и запись при уходе последнего клиента.
//
// Формат. Кадр правки: ASCII-префикс `sfu1:`, номер из 8 ASCII-байт (клиент пишет hex), дальше
// сам Yjs-апдейт. Подтверждение: `sfa1:` и те же 8 байт. Сервер номер не разбирает — он обязан
// только вернуть его отправителю без изменений, поэтому формат номера остаётся делом клиента.
//
// Почему префикс, а не байт типа. Так же устроены присутствие (`sfp1:`) и сигнал чата (`sfc1:`):
// старый клиент, который шлёт голые апдейты, продолжает работать, а новый кадр узнаётся по
// началу строки — читать бинарный формат Yjs для этого не нужно.

const (
	// updatePrefix — начало кадра правки от клиента.
	updatePrefix = "sfu1:"
	// ackPrefix — начало кадра подтверждения от сервера.
	ackPrefix = "sfa1:"
	// ackIDSize — длина номера правки.
	ackIDSize = 8
	// minUpdateFrame — самый короткий осмысленный кадр правки: префикс, номер и хоть один байт
	// апдейта. Отдельного предела размера не нужно: соединение уже ограничено maxMessageSize.
	minUpdateFrame = len(updatePrefix) + ackIDSize + 1
)

// splitUpdateFrame отделяет номер правки от самого апдейта.
//
// ok=false — кадр испорчен (обрезан): такой не применяем, иначе сервер применил бы чужие байты
// и подтвердил их клиенту.
func splitUpdateFrame(data []byte) (id, payload []byte, ok bool) {
	if len(data) < minUpdateFrame {
		return nil, nil, false
	}
	return data[len(updatePrefix) : len(updatePrefix)+ackIDSize],
		data[len(updatePrefix)+ackIDSize:], true
}

// ackFrame собирает кадр подтверждения: префикс и номер, ровно те же байты, что прислал клиент.
func ackFrame(id []byte) []byte {
	out := make([]byte, 0, len(ackPrefix)+len(id))
	out = append(out, ackPrefix...)
	return append(out, id...)
}

// enqueue ставит кадр в очередь отправки этого клиента.
//
// Через канал, а не прямо в соединение: писатель у клиента один (см. `client.writer`), и второй
// писатель из читателя гонялся бы с ним за одно соединение. Переполнение очереди — клиент не
// успевает читать; закрываем соединение, чтобы он переподключился и дослал состояние.
func (c *client) enqueue(msg []byte) {
	select {
	case c.send <- msg:
	default:
		_ = c.conn.Close()
	}
}
