package assistant

// stream.go — поток ответа помощника: события, которые уходят в браузер по мере работы.
//
// Зачем события, а не «подожди и получи JSON». Модель думает десятками секунд, а
// инструменты выполняются ещё до ответа: без потока человек видит только «думает…» и
// не отличает работу от зависания. Поэтому сервер отдаёт по ходу дела:
//
//	delta  — кусок текста ответа (может приходить много раз);
//	call   — что помощник сделал (создал главу, отказался, ошибся);
//	change — что изменилось в проекте (по этому интерфейс открывает кадр);
//	done   — итог целиком: тот же JSON, что и у обычного ответа;
//	error  — сбой ПОСЛЕ начала потока (до первого события ошибка уходит обычным
//	         ответом с кодом: интерфейс по коду понимает, что показать — согласие,
//	         ключ, права).
//
// События — надстройка, а не второй путь исполнения: тот же SendStream вызывается и
// без emitter (обычный POST), и тогда поведение прежнее. Двух реализаций цикла
// «спросили модель → выполнили инструменты» быть не должно: они разойдутся.

import (
	"context"
	"errors"
)

// Виды событий потока.
const (
	// EventStart — беседа определена (она могла быть только что создана): в поле
	// ConversationID её идентификатор.
	//
	// Нужен именно первым: без него интерфейс узнал бы, куда попал ответ, только из
	// итогового события — а если человек остановит ответ раньше, следующий вопрос
	// завёл бы ВТОРУЮ беседу, и сохранённый кусок остался бы в первой, то есть пропал
	// бы из переписки.
	EventStart = "start"
	// EventDelta — приращение текста ответа.
	EventDelta = "delta"
	// EventCall — один выполненный вызов инструмента.
	EventCall = "call"
	// EventChange — одно изменение в проекте.
	EventChange = "change"
	// EventDone — конец: итог целиком (в поле turn).
	EventDone = "done"
	// EventError — сбой после начала потока.
	EventError = "error"
)

// Event — одно событие потока.
//
// Поля необязательные: у start заполнен ConversationID, у delta — Text, у call — Call,
// у change — Change, у done — Turn. Так интерфейсу не нужно разбирать «что именно
// пришло» по нескольким похожим событиям.
type Event struct {
	Type           string  `json:"type"`
	ConversationID string  `json:"conversation_id,omitempty"`
	Text           string  `json:"text,omitempty"`
	Call           *Call   `json:"call,omitempty"`
	Change         *Change `json:"change,omitempty"`
	Turn           *Turn   `json:"turn,omitempty"`
	Error          string  `json:"error,omitempty"`
}

// Emitter отправляет событие человеку. Ошибка означает, что писать больше некуда
// (соединение закрыто) — генерацию нужно прекратить, а не копить текст в никуда.
type Emitter func(Event) error

// errStreamStopped — поток оборван на стороне человека: кнопка «стоп» или закрытая
// вкладка. Не сбой, а обычное действие, и ответ на него — сохранить то, что успело
// прийти.
var errStreamStopped = errors.New("поток остановлен")

// stoppedByClient — оборван ли поток человеком, а не сломан ли провайдер.
//
// Два источника: отмена контекста запроса (браузер закрыл соединение — так работает
// «стоп» в интерфейсе) и ошибка записи события (соединение отвалилось по дороге).
// Всё остальное — сбой, о котором надо сказать.
func stoppedByClient(err error) bool {
	return errors.Is(err, context.Canceled) || errors.Is(err, errStreamStopped)
}
