package ai

// agent.go — личность агента: имя, идентификатор и умолчания.
//
// Зачем агенту имя и своя запись в базе. Помощник правит текст проекта — значит, он
// автор правок, а не «функция владельца». Без этого в истории («кто написал главу?»)
// стоял бы человек, который её не писал, а список участников не показывал бы, что в
// проекте работает ещё один автор. Поэтому у агента есть
//   - **имя** (одна константа: меняется в одном месте, если владелец захочет другое);
//   - **строка в users** с фиксированным идентификатором и недействительным хешем
//     пароля (войти под ней нельзя) — на неё ссылаются created_by/updated_by и
//     team_memberships;
//   - **роль и указания владельца** на конкретный проект (таблица project_ai_settings):
//     в одной истории нужен строгий летописец, в другой — соавтор-фантаст.
//
// Имя выбрано по деятельности: Нестор — летописец, то есть человек, который ведёт
// хронику событий по порядку. Это ровно то, чем занят таймлайн: главы и под-события
// выстраиваются в хронологию. Имя известное, короткое и склоняется по-русски, поэтому
// в интерфейсе читается как имя соавтора, а не как название функции.

import "github.com/google/uuid"

const (
	// AgentName — имя, под которым агент виден в проекте: в чате, в списке
	// участников и как автор созданных кадров.
	AgentName = "Нестор"
	// AgentUsername — ник для поиска людей и упоминаний (/coauthors).
	AgentUsername = "nestor"
	// AgentEmail — служебный адрес: по нему нельзя зарегистрироваться или войти.
	AgentEmail = "agent@skyfraze.local"
)

// AgentUserID — фиксированный идентификатор системного пользователя агента.
//
// Совпадает с тем, что вставляет миграция 0010. Совпадение обязательно: иначе правки
// агента ссылались бы на несуществующего пользователя и теряли автора. Менять нельзя —
// он записан в уже созданных строках событий.
var AgentUserID = uuid.MustParse("00000000-0000-0000-0000-0000000000a1")

// AgentRolePresets — роли, которые владелец выбирает в интерфейсе.
//
// Список короткий намеренно: «роль» — это не характер в свободной форме, а рамка,
// которая задаёт, как агент вмешивается в проект. Свои слова владелец добавляет
