/**
 * Жива ли стадия таймлайна — решается по геометрии, а не «на глаз».
 *
 * Зачем отдельная функция. Стадия — fixed-слой на весь экран и непрозрачный: пока он
 * жив, он перекрывает всё, что лежит в потоке под треком (панель редакторов), и крадёт
 * по нему клики. Раньше условие было одно — «трек занимает больше половины экрана» — и
 * этого мало: когда внизу показывается редактор, верхнюю половину ещё занимает хвост
 * трека, стадия остаётся живой и накрывает редактор. Человек видел «пустую область» и
 * не мог работать, пока не долистает до конца.
 *
 * Поэтому правил два, и они оба обязательны:
 *   1. трек должен занимать существенную часть экрана (иначе стадии показывать нечего);
 *   2. следующий за стадией блок (панель редакторов) ещё НЕ вошёл в экран.
 *
 * Второе правило и есть исправление: как только редактор показывается — стадия гаснет.
 */
export interface StageVisibilityInput {
  /** Верх трека в координатах вьюпорта. */
  trackTop: number
  /** Низ трека в координатах вьюпорта. */
  trackBottom: number
  /** Верх видимой области (0 у окна). */
  boxTop: number
  /** Низ видимой области. */
  boxBottom: number
  /**
   * Верх следующего за стадией содержательного блока (панель редакторов) или `null`,
   * если после стадии ничего нет (пустой проект).
   */
  nextTop: number | null
  /** Какую долю экрана должен занимать трек, чтобы стадия жила. */
  minTrackShare?: number
  /** До какой доли экрана может подняться следующий блок, прежде чем стадия погаснет. */
  nextEnterRatio?: number
}

export function stageIsActive(input: StageVisibilityInput): boolean {
  const viewport = Math.max(1, input.boxBottom - input.boxTop)
  const visibleTrack =
    Math.min(input.trackBottom, input.boxBottom) - Math.max(input.trackTop, input.boxTop)

  const minShare = input.minTrackShare ?? 0.5
  if (visibleTrack <= viewport * minShare) return false

  if (input.nextTop === null) return true
  // Следующий блок входит в экран (его верх поднялся выше «линии входа») — стадия
  // гаснет, чтобы не перекрывать редактор. Линия чуть выше низа экрана: пока блок
  // только-только показался снизу, стадия уже не нужна.
  const enterLine = input.boxTop + viewport * (input.nextEnterRatio ?? 0.9)
  return input.nextTop > enterLine
}
