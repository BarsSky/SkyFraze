/**
 * Политика «живого» окна Markdown: что делать, когда в CRDT приехал новый текст,
 * а окно уже открыто.
 *
 * Проблема была простой и дорогой: `MarkdownEditor` держал локальную копию
 * (`useState(value)`) и отдавал её только по «Сохранить». Пока окно открыто,
 * чужие правки `body` в него не попадали, а сохранение затирало их локальной
 * копией. Соавтор печатал — текст исчезал без следа.
 *
 * Решение: решение о том, что показать, вынесено в чистую функцию, а компонент
 * лишь исполняет её. Так правило живёт в одном месте и проверяется тестом, а не
 * тремя `useState` в JSX.
 */

/** Текст как он есть в CRDT на момент рендера — база сравнения. */
export interface LiveTextInput {
  /** Что сейчас в поле ввода (черновик пользователя). */
  local: string
  /** Версия текста, которую человек видел «сохранённой» последней. */
  base: string
  /** Свежий текст из CRDT. */
  remote: string
}

export type LiveTextResolution =
  /** Новый текст — наша же запись или не про этот документ: просто обновляем базу. */
  | { action: 'ignore'; base: string }
  /** Несохранённых правок нет: молча показываем пришедшее. */
  | { action: 'adopt'; base: string; text: string }
  /** Пользователь печатает: его черновик не трогаем, но показываем предупреждение. */
  | { action: 'notify'; base: string }

/**
 * Порядок проверок важен:
 *
 * 1. `remote === local` — правка из CRDT догнала черновик (типичный случай, когда
 *    сохранение ушло, и апдейт вернулся эхом). Затирать нечего, предупреждать
 *    не о чем.
 * 2. `remote === base` — изменения не касаются этого текста (кто-то правил
 *    заголовок события): окно трогать не нужно.
 * 3. `local === base` — черновика нет, можно молча принять версию соавтора.
 * 4. Иначе — есть несохранённые правки И пришёл другой текст: показываем
 *    предупреждение, ничего не затирая. Решение принимает человек.
 */
export function resolveLiveText({ local, base, remote }: LiveTextInput): LiveTextResolution {
  if (remote === local) return { action: 'ignore', base: remote }
  if (remote === base) return { action: 'ignore', base }
  if (local === base) return { action: 'adopt', base: remote, text: remote }
  return { action: 'notify', base: remote }
}
