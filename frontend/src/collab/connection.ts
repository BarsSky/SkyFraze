/**
 * Состояние realtime-соединения как одно значение.
 *
 * Раньше наружу торчал только булев `connected`, и страница не могла отличить
 * «сеть пропала, сейчас переподключимся» от «realtime здесь недоступен вовсе»
 * (прокси без Upgrade, запрет `ws://` на HTTPS-странице). Это разные ситуации и
 * разные сообщения человеку, поэтому состояние — перечисление, а текст для
 * интерфейса считает одна чистая функция (её и проверяет тест).
 */
export type CollabStatus =
  /** Первое подключение, ответа от сервера ещё не было. */
  | 'connecting'
  /** Сокет открыт: правки летят другим сразу. */
  | 'open'
  /** Соединение было, оборвалось и повторяется по бэкоффу. */
  | 'reconnecting'
  /** Повторы уже несколько раз не удались — похоже, realtime тут недоступен. */
  | 'offline'

/** После скольких неудачных попыток подряд считаем, что связи нет, а не «мигнуло». */
export const OFFLINE_AFTER_ATTEMPTS = 3

/** Единственное место, где состояние превращается в человеческий текст. */
export function connectionNotice(status: CollabStatus, attempt: number): string | null {
  switch (status) {
    case 'connecting':
      return null
    case 'open':
      return null
    case 'reconnecting':
      return 'Связь с realtime-сервером прервалась, переподключаюсь…'
    case 'offline':
    default:
      return attempt >= OFFLINE_AFTER_ATTEMPTS
        ? 'realtime недоступен: правки сохраняются, но другие вкладки увидят их после перезагрузки'
        : 'Связь с realtime-сервером прервалась, переподключаюсь…'
  }
}
