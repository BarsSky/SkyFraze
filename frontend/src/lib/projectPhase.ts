import type { ContentState } from '../collab/yprovider'

/**
 * Что показывает страница проекта: загрузку, честный отказ или содержимое.
 *
 * Зачем отдельная функция. «Пусто» и «ещё не приехало» в интерфейсе выглядят
 * одинаково, и страница показывала заглушку «Таймлайн пока пуст» (с кнопкой «Добавить
 * первую главу») на каждом открытии проекта, пока снапшот ехал по сети. На медленной
 * связи это не только выглядело как «проект пуст», но и давало нажать кнопку и
 * создать лишнюю главу.
 *
 * Три состояния, которые нельзя путать:
 *
 *   * `loading` — снапшот ещё едет (или неизвестна роль): показываем анимацию;
 *   * `failed` — прочитать не удалось: показываем отказ и «Повторить». Это НЕ пустой
 *     проект, и говорить «таймлайн пуст» здесь нельзя;
 *   * `ready` — знаем содержимое: дальше страница решает сама (пусто / таймлайн).
 *
 * Роль (`projectKnown`) проверяется вместе с контентом: от неё зависит, что показывать
 * в пустом проекте — «создайте первую главу» редактору или «автор ещё не добавил» читателю.
 * Пока роль неизвестна, показывать любой из этих текстов — угадывание.
 */
export type ProjectPhase = 'loading' | 'failed' | 'ready'

export interface ProjectPhaseInput {
  /** Пришёл ли проект (вместе с ним — роль пользователя). */
  projectKnown: boolean
  /** Состояние загрузки содержимого из collab-провайдера. */
  content: ContentState
  /** Сколько событий в документе; `-1` — документа ещё нет. */
  eventsCount: number
  /** Ошибка загрузки проекта: её показывает баннер, и фазой управлять не нужно. */
  failed?: boolean
}

export function projectPhase(input: ProjectPhaseInput): ProjectPhase {
  // Ошибку загрузки проекта показывает баннер — отдельной фазе здесь делать нечего.
  if (input.failed) return 'ready'
  if (input.content === 'failed') return 'failed'
  if (!input.projectKnown) return 'loading'
  if (input.content === 'loading' || input.eventsCount < 0) return 'loading'
  return 'ready'
}
