/** Короткая подпись специализации для чипа в списке. */
export function craftShort(craft: string): string {
  const cut = craft.split(/ и |:/)[0].trim()
  return cut.length > 0 ? cut : craft
}

/** Специализации приходят из API как null — приводим к массиву. */
export function craftsOf(value: string[] | null | undefined): string[] {
  return Array.isArray(value) ? value : []
}
